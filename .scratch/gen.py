#!/usr/bin/env python3
"""Generate js/data.js (Poriborton MAP) and tests/poriborton-pairs.json.

Sources (MIT, OpenBangla Poriborton, cloned to /tmp/Poriborton):
  src/bijoy2000.rs  -- MAP: Unicode cluster -> Bijoy 2000 code
  tests/bijoy2000.rs -- 681 assert_eq(unicode_to_bijoy(uni), bijoy) pairs

Everything emitted is pure ASCII: non-ASCII chars become \\uXXXX escapes,
so the factory push path (argv JSON) can never corrupt Bengali text.
"""
import json
import re
import sys
from pathlib import Path

PORI = Path("/tmp/Poriborton")
OUT = Path(__file__).resolve().parent.parent  # builds/bijoy-unicode-bd


def esc(s: str) -> str:
    """Escape a string to pure ASCII with \\uXXXX for every non-ASCII char."""
    out = []
    for ch in s:
        o = ord(ch)
        if o < 0x20 or o == 0x7F:
            out.append("\\u%04x" % o)
        elif o < 0x80:
            out.append("\\" if ch == "\\" else '"' if ch == '"' else ch)
        elif o <= 0xFFFF:
            out.append("\\u%04x" % o)
        else:
            # surrogate pair
            o -= 0x10000
            out.append("\\u%04x\\u%04x" % (0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)))
    return "".join(out)


def main() -> int:
    rs = (PORI / "src/bijoy2000.rs").read_text(encoding="utf-8")
    # MAP entries look like:    "ক" => "K",
    entries = re.findall(r'^\s*"((?:[^"\\]|\\.)*)"\s*=>\s*"((?:[^"\\]|\\.)*)",\s*$',
                         rs, re.M)
    if not entries:
        print("FATAL: no MAP entries parsed", file=sys.stderr)
        return 1

    def unesc(s: str) -> str:
        return s.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8") \
            if "\\" in s else s

    # Rust string literals here only use plain chars (no backslash escapes except "\\\\")
    pairs = []
    for k, v in entries:
        kk = k.replace("\\\\", "\\")
        vv = v.replace("\\\\", "\\")
        pairs.append((kk, vv))
    print(f"MAP entries parsed: {len(pairs)}")

    # Collision report for the reverse direction (two Unicode keys -> same Bijoy code)
    from collections import defaultdict
    by_val = defaultdict(list)
    for k, v in pairs:
        by_val[v].append(k)
    collisions = {v: ks for v, ks in by_val.items() if len(ks) > 1}
    print(f"reverse collisions (same Bijoy code from >1 Unicode key): {len(collisions)}")
    for v, ks in sorted(collisions.items()):
        print(f"  Bijoy {v!r} <- {[k for k in ks]}")

    # Longest Bijoy code length (for longest-match tokenisation)
    print(f"max Bijoy code length: {max(len(v) for _, v in pairs)} chars")
    print(f"max Unicode key length: {max(len(k) for k, _ in pairs)} chars")

    # Emit js/data.js
    lines = []
    lines.append("// GENERATED by .scratch/gen.py from OpenBangla Poriborton (MIT).")
    lines.append("// Do not hand-edit: re-run gen.py. All strings are pure ASCII")
    lines.append("// (non-ASCII as \\uXXXX escapes) so pushes stay ASCII-safe.")
    lines.append("// MAP: Unicode Bengali cluster -> Bijoy 2000 (SutonnyMJ) code.")
    lines.append("// Source: github.com/OpenBangla/Poriborton src/bijoy2000.rs")
    lines.append("'use strict';")
    lines.append("const BIJOY_MAP = {")
    for k, v in pairs:
        lines.append('  "%s": "%s",' % (esc(k), esc(v)))
    lines.append("};")
    lines.append("if (typeof module !== 'undefined') module.exports = { BIJOY_MAP };")
    (OUT / "js/data.js").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote js/data.js ({(OUT / 'js/data.js').stat().st_size} bytes)")

    # Extract test pairs from tests/bijoy2000.rs AND the inline #[cfg(test)]
    # module in src/bijoy2000.rs AND the doc example in src/lib.rs.
    raw = []
    for rel in ["tests/bijoy2000.rs", "src/bijoy2000.rs", "src/lib.rs"]:
        tests = (PORI / rel).read_text(encoding="utf-8")
        # assert_eq!(unicode_to_bijoy("..."), "...");  -- strings may contain \\u{...} escapes
        found = re.findall(r'unicode_to_bijoy\("((?:[^"\\]|\\.)*)"\),\s*"((?:[^"\\]|\\.)*)"\)', tests)
        print(f"  {rel}: {len(found)} pairs")
        raw.extend(found)
    print(f"raw assert pairs found: {len(raw)}")

    def rust_unesc(s: str) -> str:
        # \u{XXXX} escapes + \\ + \"  (Rust syntax)
        def sub(m):
            return chr(int(m.group(1), 16))
        s = re.sub(r"\\u\{([0-9a-fA-F]+)\}", sub, s)
        return s.replace("\\\\", "\\").replace('\\"', '"')

    parsed = []
    seen = set()
    for uni, bij in raw:
        u = rust_unesc(uni)
        b = rust_unesc(bij)
        if (u, b) in seen:
            continue
        seen.add((u, b))
        parsed.append([u, b])
    print(f"unique test pairs: {len(parsed)}")

    # Emit as JSON with ensure_ascii=True (\\uXXXX escapes)
    payload = {"source": "OpenBangla/Poriborton tests/bijoy2000.rs (MIT)",
               "count": len(parsed), "pairs": parsed}
    (OUT / "tests/poriborton-pairs.json").write_text(
        json.dumps(payload, ensure_ascii=True, indent=1) + "\n", encoding="ascii")
    print(f"wrote tests/poriborton-pairs.json "
          f"({(OUT / 'tests/poriborton-pairs.json').stat().st_size} bytes)")

    # Hand-checked extra pairs (Poriborton docs + teamzlab reference page).
    # Written here in UTF-8 Python source; emitted ASCII-escaped JSON so no
    # hand-written pushed file ever contains raw Bengali. The "য়" below is
    # always the single letter U+09DF (written as an escape to be explicit);
    # the ZWNJ in the unlisted-conjunct pair is U+200C (also explicit).
    extra = [
        ["আমি বাংলা\u09df গান গাই", "Avwg evsjvq Mvb MvB"],
        ["বিজ\u09df ২০০০", "weRq 2000"],
        ["বাংলা আমার ভাষা। আমি বাংলা\u09df দেখি স্বপ্ন!",
         "evsjv Avgvi fvlv| Avwg evsjvq †`wL ¯^cœ!"],
        ["আমি", "Avwg"],
        ["কে", "†K"],
        ["কো", "†Kv"],
        ["কৌ", "†KŠ"],
        ["ধর্ম", "ag©"],
        ["প্রকাশ", "cÖKvk"],
        ["কিন্তু", "wKš‘"],
        ["ক্ষমা", "¶gv"],
        ["বাংলা", "evsjv"],
        ["অর্ক", "AK©"],
        ["কর্তা", "KZ©v"],
        ["সংখ্যা", "msL¨v"],
        ["বিদ্যুৎ", "we`¨yr"],
        ["র\u200d্যাব", "i¨ve"],
        ["ফিনান্সিয়াল", "wdbvwÝqvj"],
        ["স্প\u09cd\u200cল", "¯c&j"],
        ["ক্", "K&"],
        ["্", "&"],
        ["০১২৩৪৫৬৭৮৯৳।॥", "0123456789$|\\"],
        ["“আজো তার ফুলকলিদের ঘুম টুটেনি, তন্দ্রাতে বিলোল”",
         "ÒAv‡Rv Zvi dzjKwj‡`i Nyg Uz‡Uwb, Z›`ªv‡Z we‡jvjÓ"],
        ["ঢাকা, বাংলাদেশ।", "XvKv, evsjv‡`k|"],
        ["ক\nখ", "K\nL"],
        ["জ\u09cd\u200cম", "R&g"],  # unlisted conjunct: explicit hasant + ZWNJ
    ]
    payload = {"source": "hand-checked (Poriborton docs, teamzlab reference)",
               "count": len(extra), "pairs": extra}
    (OUT / "tests/extra-pairs.json").write_text(
        json.dumps(payload, ensure_ascii=True, indent=1) + "\n", encoding="ascii")
    print(f"wrote tests/extra-pairs.json "
          f"({(OUT / 'tests/extra-pairs.json').stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
